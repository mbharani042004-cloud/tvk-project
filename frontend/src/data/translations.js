/* Pick the right string from bilingual mock content. Accepts either a plain
   string (user-submitted data) or an { en, ta } object (seed data). */
export function localize(field, language) {
  if (field === null || field === undefined) return '';
  if (typeof field === 'string') return field;
  return field[language] ?? field[DEFAULT_LANGUAGE] ?? '';
}

/* Resolve a dot-path key (e.g. "nav.home") for a language, with English fallback. */
export function resolveTranslation(language, key, fallbackLanguage = DEFAULT_LANGUAGE) {
  const read = (lang) =>
    key.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), lang);

  const value = read(translations[language]);
  if (value !== undefined) return value;

  const fallback = read(translations[fallbackLanguage]);
  return fallback !== undefined ? fallback : key;
}
